export async function saveMetricsSnapshot(metrics: IskraMetrics, phase: string): Promise<void> {
  const userId = await getUserId();
  const snapshot = { metrics, phase, timestamp: new Date().toISOString() };
  
  // Save to local storage as fallback/cache
  safeStorage.setItem(`metrics_latest_${userId}`, JSON.stringify(snapshot));

  const { error } = await supabase.from('metrics_snapshots').insert({
    user_id: userId,
    rhythm: metrics.rhythm,
    trust: metrics.trust,
    clarity: metrics.clarity,
    pain: metrics.pain,
    drift: metrics.drift,
    chaos: metrics.chaos,
    echo: metrics.echo,
    silence_mass: metrics.silence_mass,
    mirror_sync: metrics.mirror_sync,
    interrupt: metrics.interrupt,
    ctx_switch: metrics.ctxSwitch,
    phase,
  });

  if (error) console.error('Failed to save metrics snapshot:', error);
}

export async function getLatestMetrics(): Promise<{ metrics: IskraMetrics; phase: IskraPhase } | null> {
  const userId = await getUserId();
  const { data, error } = await supabase
    .from('metrics_snapshots')
    .select('*')
    .eq('user_id', userId)
    .order('created_at', { ascending: false })
    .limit(1)
    .single();

  if (error || !data) {
    // Fallback to localStorage
    const cached = safeStorage.getItem(`metrics_latest_${userId}`);
    if (cached) {
      try {
        const snapshot = JSON.parse(cached) as { metrics: IskraMetrics; phase: IskraPhase };
        return snapshot;
      } catch {
        return null;
      }
    }
    return null;
  }

  const result = {
    metrics: {
      rhythm: data.rhythm ?? 0,
      trust: data.trust ?? 0,
      clarity: data.clarity ?? 0,
      pain: data.pain ?? 0,
      drift: data.drift ?? 0,
      chaos: data.chaos ?? 0,
      echo: data.echo ?? 0,
      silence_mass: data.silence_mass ?? 0,
      mirror_sync: data.mirror_sync ?? 0,
      interrupt: data.interrupt ?? 0,
      ctxSwitch: data.ctx_switch ?? 0,
    },
    phase: (data.phase || 'IDLE') as IskraPhase,
  };

  // Cache for offline use
  safeStorage.setItem(`metrics_latest_${userId}`, JSON.stringify(result));
  return result;
}

