export async function getMemoryNodes(layer?: string): Promise<MemoryNode[]> {
  const userId = await getUserId();
  let query = supabase
    .from('memory_nodes')
    .select('*')
    .eq('user_id', userId)
    .order('created_at', { ascending: false });

  if (layer) {
    query = query.eq('layer', layer);
  }

  const { data, error } = await query;

  if (error) {
    console.error('Failed to get memory nodes:', error);
    // Fallback to localStorage
    const cacheKey = layer ? `memory_${layer}_${userId}` : `memory_all_${userId}`;
    const cached = safeStorage.getItem(cacheKey);
    if (cached) {
      try {
        return JSON.parse(cached) as MemoryNode[];
      } catch {
        return [];
      }
    }
    return [];
  }

  const nodes: MemoryNode[] = (data || []).map(row => ({
    id: row.id,
    type: row.type as any,
    layer: row.layer as any,
    timestamp: row.created_at || new Date().toISOString(),
    title: row.title || '',
    content: row.content,
    doc_type: row.doc_type as any || undefined,
    trust_level: row.trust_level ?? undefined,
    tags: row.tags || [],
    section: row.section || undefined,
    facet: row.facet as any || undefined,
    evidence: (row.evidence as unknown as SIFTBlock[]) || [],
  }));

  // Cache for offline use
  const cacheKey = layer ? `memory_${layer}_${userId}` : `memory_all_${userId}`;
  safeStorage.setItem(cacheKey, JSON.stringify(nodes));
  return nodes;
}

export async function addMemoryNode(node: Omit<MemoryNode, 'id' | 'timestamp'>): Promise<MemoryNode> {
  const userId = await getUserId();
  const { data, error } = await supabase
    .from('memory_nodes')
    .insert({
      user_id: userId,
      layer: node.layer,
      type: node.type,
      title: node.title,
      content: node.content as any,
      doc_type: node.doc_type || null,
      trust_level: node.trust_level || 1.0,
      tags: node.tags || [],
      section: node.section || null,
      facet: node.facet || null,
      evidence: node.evidence as any || [],
    })
    .select()
    .single();

  if (error) throw error;

  return {
    id: data.id,
    type: data.type as any,
    layer: data.layer as any,
    timestamp: data.created_at || new Date().toISOString(),
    title: data.title || '',
    content: data.content,
    doc_type: data.doc_type as any || undefined,
    trust_level: data.trust_level ?? 1.0,
    tags: data.tags || [],
    evidence: [],
  };
}

