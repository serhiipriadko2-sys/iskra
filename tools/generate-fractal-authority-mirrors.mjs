import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import process from 'node:process'

const ROOT = resolve(import.meta.dirname, '..')
const GENERATOR_VERSION = 'fractal-authority-generator-v1'
const BANNER = '// GENERATED by tools/generate-fractal-authority-mirrors.mjs. DO NOT EDIT.\n'
const CHECK_ONLY = process.argv.includes('--check')

const canonical = {
  source: 'packages/math/src/fractal-authority-source.ts',
  contracts: 'packages/math/src/fractal-authority-contracts.ts',
  wrapper: 'packages/math/src/fractal-authority.ts',
  provenance: 'packages/math/src/fractal-authority-provenance.ts',
  corpus: 'packages/math/src/fractal-authority-corpus.json',
}

const mirrors = [
  { root: 'runtime/src/types', importExtension: '.js' },
  { root: 'supabase/functions/_shared/iskra-metrics', importExtension: '.ts' },
]

function sha256(content) {
  return createHash('sha256').update(content).digest('hex')
}

function mirrorImports(content, extension) {
  return content.replaceAll(".js'", `${extension}'`)
}

function buildProvenance(sourceHash, generatedArtifactHash, corpusHash) {
  return [
    "export const HFD_ALGORITHM_VERSION = 'hfd-v1-kmax5'",
    "export const DFA_ALGORITHM_VERSION = 'dfa-v1-min50-box4-16'",
    `export const FRACTAL_GENERATOR_VERSION = '${GENERATOR_VERSION}'`,
    'export const FRACTAL_CANONICAL_SOURCE_HASH =',
    `  '${sourceHash}'`,
    'export const FRACTAL_GENERATED_ARTIFACT_HASH =',
    `  '${generatedArtifactHash}'`,
    'export const FRACTAL_PARITY_CORPUS_HASH =',
    `  '${corpusHash}'`,
    '',
  ].join('\n')
}

async function read(relativePath) {
  return readFile(resolve(ROOT, relativePath), 'utf8')
}

async function ensure(relativePath, expected) {
  const absolutePath = resolve(ROOT, relativePath)
  let actual = null
  try {
    actual = await readFile(absolutePath, 'utf8')
  } catch {
    actual = null
  }

  if (actual === expected) return
  if (CHECK_ONLY) {
    throw new Error(`generated drift: ${relativePath}`)
  }
  await writeFile(absolutePath, expected, 'utf8')
}

const source = await read(canonical.source)
const contracts = await read(canonical.contracts)
const wrapper = await read(canonical.wrapper)
const corpus = await read(canonical.corpus)
const generatedSource = `${BANNER}${source}`
const provenance = buildProvenance(
  sha256(source),
  sha256(generatedSource),
  sha256(corpus),
)

await ensure(canonical.provenance, provenance)
for (const mirror of mirrors) {
  await ensure(`${mirror.root}/fractal-authority-source.ts`, generatedSource)
  await ensure(
    `${mirror.root}/fractal-authority-provenance.ts`,
    `${BANNER}${provenance}`,
  )
  await ensure(
    `${mirror.root}/fractal-authority-contracts.ts`,
    `${BANNER}${mirrorImports(contracts, mirror.importExtension)}`,
  )
  await ensure(
    `${mirror.root}/fractal-authority.ts`,
    `${BANNER}${mirrorImports(wrapper, mirror.importExtension)}`,
  )
}

console.log(
  JSON.stringify(
    {
      status: 'pass',
      check_only: CHECK_ONLY,
      generator_version: GENERATOR_VERSION,
      canonical_source_hash: sha256(source),
      generated_artifact_hash: sha256(generatedSource),
      parity_corpus_hash: sha256(corpus),
    },
    null,
    2,
  ),
)
